// Package renderer produces the deterministic, per-profile desired operand
// sets for the Quartet reconciler.
//
// Design constraints:
// - EXPLICIT per-profile structs behind a fixed switch — no generic plugin
// mechanism and no dynamic registration.
// - Field-level canonical values come from the pinned raw driver manifests
// (each driver repository's deploy/manifest), mirrored field-level by the
// golden fixtures in testdata/<profile>-{k8s,ocp}-golden.yaml with only
// the approved transforms layered on. The renderer must not deviate from
// that set; the golden-parity tests pin it against the raw renders.
// - The renderer never invents objects outside the owner matrix:
// no StorageClass/VolumeSnapshotClass, no Secret (the spec secretRef only
// feeds the objects' env secretKeyRefs), no helm-only test-connection Pod.
// - The renderer produces the desired state WITHOUT operator ownership
// metadata; the reconciler stamps the owner-uid annotation and applies
// with the field manager.
package renderer

import (
	"github.com/ngxstorage/quartet-operator/api/v1alpha1"
	"sigs.k8s.io/controller-runtime/pkg/client"
)

// Operator identity constants: the SSA field manager and the ownership
// annotation key. The annotation VALUE is the Quartet CR UID.
const (
	// FieldManager is the server-side-apply field owner for every operand.
	FieldManager = "quartet-operator"
	// OwnerUIDAnnotation marks an object as managed by a specific Quartet
	// CR; its value is the CR UID (UID-verified ownership).
	OwnerUIDAnnotation = "quartet.ngxstorage.com/owner-uid"
)

// ProfileInput is the reconciler-side projection of the spec fields one
// profile renderer consumes. SecretRef.Name feeds the env secretKeyRefs
// only; the Secret itself is user-owned.
type ProfileInput struct {
	// Profile name: nfs, fc or iscsi (the typed API admits exactly these
	// three; anything else makes For return nil and the reconciler
	// reports RenderError, never disabled-or-Ready).
	Profile string
	// SecretName is spec.profiles.<p>.secretRef.name.
	SecretName string
	// DriverImage is spec.profiles.<p>.image.reference — a full OCI digest
	// reference. Sidecar images are renderer constants pinned from the raw
	// driver manifests.
	DriverImage string
	// LogLevel is spec.logLevel, rendered into --log=<level> UNQUOTED.
	LogLevel string
	// Platform is the reconciler-resolved platform.
	Platform v1alpha1.Platform
}

// Profile is the explicit per-profile render contract. Implementations are
// fixed structs produced by For — there is no registration path.
type Profile interface {
	// Name is the profile key (nfs).
	Name() string
	// Namespace is the operand namespace ("ngxstorage-<profile>").
	// The reconciler ensures it but never deletes it.
	Namespace() string
	// Objects is the deterministic desired operand set in the reconciler's
	// apply order (RBAC/SA → platform policy → coordination → CSIDriver →
	// Service → Deployment → DaemonSet). Never includes the Namespace, a
	// Secret, SC/VSC or the helm-only test-connection Pod.
	Objects() []client.Object
	// InstallRBAC returns the profile's operand RBAC set — the Role,
	// RoleBinding, ClusterRole and ClusterRoleBinding objects Objects()
	// renders for this profile's platform. The reconciler NEVER applies
	// these at runtime (out-of-band provisioning): the INSTALLER applies
	// them from the committed manifests generated by
	// hack/generate-install-rbac (config/operands/<profile>/), and the
	// reconciler only VERIFIES their health at reconcile start (RBACDrift
	// gate). They stay in Objects() so the golden parity fixtures cover
	// the full render; the runtime apply set is Objects() minus
	// InstallRBAC().
	InstallRBAC() []client.Object
	// OperandKinds returns the operand resource kinds the profile creates,
	// for owned-object ENUMERATION during disable/delete cleanup. A profile
	// disabled via spec no longer appears in Objects(), so cleanup must
	// list-and-match by owner-uid annotation instead. Scope is explicit
	// because enumeration must not rely on API discovery (SCC unstructured
	// is not in any built-in scope table). RBAC kinds are ABSENT: operand
	// RBAC is installer-owned out-of-band (InstallRBAC), so cleanup never
	// enumerates or deletes it.
	OperandKinds() []OperandKind
	// WorkloadTargets returns the profile's OWN controller Deployment and
	// node DaemonSet names, for the reconciler's per-profile readiness
	// probe. Each profile probes ITS OWN workloads in ITS OWN operand
	// namespace (Namespace()): hardcoding one profile's names would make
	// the other profiles unreachable for Ready even with healthy workloads,
	// and symmetrically let a ready workload planted in another profile's
	// namespace satisfy it. The values equal the names Objects() renders
	// (pinned by the renderer contract tests) and carry no user-facing API
	// field.
	WorkloadTargets() (controllerDeployment, nodeDaemonSet string)
}

// OperandKind names one operand resource kind with its enumeration scope
// and the type-safe accessors the cleanup path needs (the renderer owns the
// concrete list types, so the reconciler avoids reflection).
type OperandKind struct {
	// Object is an empty instance (typed, or unstructured with GVK set).
	Object client.Object
	// ClusterScoped selects cluster-wide enumeration.
	ClusterScoped bool
	// NewList returns an empty ObjectList for Object's type.
	NewList func() client.ObjectList
	// Items extracts the element objects from a populated list.
	Items func(client.ObjectList) []client.Object
}

// For is the fixed three-profile dispatch. A nil return means "this profile
// name is not one the typed API admits" — the reconciler reports it as
// unsupported (RenderError), never as disabled-or-Ready.
func For(input ProfileInput) Profile {
	switch input.Profile {
	case v1alpha1.ProfileNFS:
		return &nfsProfile{in: input}
	case v1alpha1.ProfileFC:
		return &fcProfile{in: input}
	case v1alpha1.ProfileISCSI:
		return &iscsiProfile{in: input}
	default:
		// Unreachable via the typed API (spec has exactly nfs/fc/iscsi);
		// stay honest instead of rendering an unknown profile.
		return nil
	}
}

// ProfileNames is the deterministic reconcile/cleanup order. The fixed
// order makes aggregate-status and partial-apply behavior reproducible
// (per-profile isolation).
func ProfileNames() []string {
	return []string{v1alpha1.ProfileNFS, v1alpha1.ProfileFC, v1alpha1.ProfileISCSI}
}

// OperandNamespace returns the operand namespace for one profile NAME
// ("ngxstorage-<profile>") without constructing the renderer — the
// controller's install-owned RBAC watch enqueuer needs it to scope the
// namespaced Role/RoleBinding pins. The value equals Profile.Namespace()
// for every rendered profile.
func OperandNamespace(profile string) string {
	return "ngxstorage-" + profile
}

// ProvisionerIdentity returns the CSI provisioner identity one profile's
// storage is recognizable by: the StorageClass/CSI driver name and the
// volumeHandle prefix the driver embeds in static PVs it created. The
// disable/delete usage gate matches cluster-wide PVs against THIS identity
// — a driver serves volumes to any workload namespace, so the gate cannot
// be scoped to the operand namespace alone. Every rendered profile
// contributes a non-empty identity (a missing one would silently let the
// gate ignore that profile's live volumes; the collision-free union is
// pinned by the controller contract tests). Unknown profile names
// contribute nothing ("", "").
//
// Handle prefixes are pinned from the driver source, not invented: FC's
// is fc.csi.ngxstorage.com. (FC driver pkg/driver/controller.go
// volumeIDPrefix) and iSCSI's is iscsi.csi.ngxstorage.com. (iSCSI driver
// pkg/driver/controller.go volumeIDPrefix).
func ProvisionerIdentity(profile string) (driverName, volumeHandlePrefix string) {
	switch profile {
	case v1alpha1.ProfileNFS:
		return nfsDriverName, nfsDriverName + "."
	case v1alpha1.ProfileFC:
		return fcDriverName, fcDriverName + "."
	case v1alpha1.ProfileISCSI:
		return iscsiDriverName, iscsiVolumeHandlePrefix
	default:
		return "", ""
	}
}

// OperandRBAC is the FIXED set of RBAC operand names one profile renderer
// produces. With the out-of-band RBAC model these names no longer appear
// in the manager's role.yaml as resourceNames pins — the manager holds
// ONLY get/list/watch on the four RBAC kinds and never mutates them at
// runtime. The names still matter as the installer's identity set:
// config/operands/<profile>/ carries exactly these objects, and the
// reconciler's RBAC health gate verifies them by pinned name at reconcile
// start (RBACDrift).
type OperandRBAC struct {
	// Roles are namespaced Role names, created in the profile's operand
	// namespace (one entry per name — the namespace is not part of the RBAC
	// identity).
	Roles []string
	// RoleBindings are namespaced RoleBinding names in the operand namespace.
	RoleBindings []string
	// ClusterRoles / ClusterRoleBindings are cluster-scoped names.
	ClusterRoles        []string
	ClusterRoleBindings []string
}

// OperandRBACNames returns the fixed RBAC operand names for one profile.
// Every rendered profile contributes its full pinned set; an unknown
// profile name contributes nothing (For returns nil for it — the same
// explicit switch, no plugin). The committed install manifests
// (config/operands/<profile>/) carry exactly these objects and are
// regenerated via hack/generate-install-rbac; the controller tests pin
// the committed install set against InstallRBAC() and the union against
// this fixed set, so the manifests and the renderers cannot drift apart.
func OperandRBACNames(profile string) OperandRBAC {
	switch profile {
	case v1alpha1.ProfileNFS:
		return nfsRBACNames
	case v1alpha1.ProfileFC:
		return fcRBACNames
	case v1alpha1.ProfileISCSI:
		return iscsiRBACNames
	default:
		return OperandRBAC{}
	}
}

// AllOperandRBACNames is the union over every rendered profile — the set
// the RBAC resourceNames markers must carry.
func AllOperandRBACNames() OperandRBAC {
	out := OperandRBAC{}
	for _, p := range ProfileNames() {
		n := OperandRBACNames(p)
		out.Roles = append(out.Roles, n.Roles...)
		out.RoleBindings = append(out.RoleBindings, n.RoleBindings...)
		out.ClusterRoles = append(out.ClusterRoles, n.ClusterRoles...)
		out.ClusterRoleBindings = append(out.ClusterRoleBindings, n.ClusterRoleBindings...)
	}
	return out
}
