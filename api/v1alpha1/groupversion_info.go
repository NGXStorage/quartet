// Package v1alpha1 contains the Quartet API types for the
// quartet.ngxstorage.com/v1alpha1 group.
//
// The CRD is quartets.quartet.ngxstorage.com, cluster-scoped, with v1alpha1 as
// the only and storage version (single version, no conversion needed).
// +groupName=quartet.ngxstorage.com
// +kubebuilder:object:generate=true
//
// RBAC surface of the Quartet manager (generated into config/rbac/role.yaml;
// the rbac markers are package-scoped in controller-gen v0.16).
//
// Deliberately ABSENT (do not add without a design decision):
// - secrets: the operator has NO Secret API access. Secret existence/key
// presence is verified by the kubelet as CreateContainerConfigError and
// reported as generic WorkloadNotReady.
//
// Operand surface: the manager creates, reads, patches (SSA) and deletes
// ONLY its owned operand kinds. NOTE: namespaces create is a standalone
// cluster-wide grant and is listed on its own line, separate from the
// operand kinds it scopes.
//
// Bounded read verbs, each with a stated need:
// - pods get;list;watch (namespaced): the workload-readiness probe lists
// operand pods for container waiting states (CreateContainerConfigError,
// ImagePullBackOff). Read-only, no pod mutation.
// - replicasets get;list (namespaced): the workload-readiness probe's
// owner-chain check lists the operand namespace's ReplicaSets to resolve
// pod → ReplicaSet → Deployment UID ownership. Read-only, one-shot direct
// read (no watch — same precedent as the uncached namespace GET).
//
// OUT-OF-BAND OPERAND RBAC: the manager holds NO mutating verb on any RBAC
// kind. A self-provisioning model (pinned delete + unrestricted
// create/escalate + pinned bind) would be an open privilege-escalation path:
// a resourceNames pin bounds the role NAME, never its CONTENT — the manager
// could delete the pinned operand ClusterRole, recreate the SAME name with
// privileged content (create+escalate carry no name into RBAC matching, so
// neither verb can be pinned), and bind it through the pinned binding names
// — compromising the existing operand binding as well. The strict end-state
// is: operand RBAC is provisioned OUT-OF-BAND by the installer — the
// renderer's InstallRBAC() set is committed as config/operands/<profile>/
// (generated by hack/generate-install-rbac, parity-pinned against the
// renderer), the admin applies it with the install manifest, and the
// reconciler only VERIFIES it by pinned name at reconcile start: missing,
// drifted rules or wrong binding subjects gate operand apply behind
// Degraded/RBACDrift (draft reason) with a retryable requeue, telling the
// admin to re-apply the install manifest. The four RBAC kinds keep ONLY
// get;list;watch: get is the health gate, and list/watch stay UNRESTRICTED
// because the informer cache and cleanup enumeration issue unfiltered
// list/watch that a resourceNames pin would Forbidden (proven against the
// real RBAC layer by the envtest watch suite). Mutation verbs on RBAC kinds
// are gone entirely; the envtest escalation suite proves delete/create/bind/
// patch of the pinned operand names are all DENIED for the token-only
// manager SA, and the role.yaml contract test pins the generated role.yaml
// to exactly this surface.
//
// FC/iSCSI install sets are implemented and live in
// config/operands/<profile>/; the parity test covers them. No placeholder
// markers are used for any profile.
//
// +kubebuilder:rbac:groups=quartet.ngxstorage.com,resources=quartets,verbs=get;list;watch;update;patch
// +kubebuilder:rbac:groups=quartet.ngxstorage.com,resources=quartets/status,verbs=get;update;patch
// +kubebuilder:rbac:groups=quartet.ngxstorage.com,resources=quartets/finalizers,verbs=update
// +kubebuilder:rbac:groups="",resources=events,verbs=create;patch
// +kubebuilder:rbac:groups=coordination.k8s.io,resources=leases,verbs=get;list;watch;create;update;patch;delete
// +kubebuilder:rbac:groups="",resources=namespaces,verbs=get;create
// +kubebuilder:rbac:groups="",resources=pods,verbs=get;list;watch
// +kubebuilder:rbac:groups=apps,resources=replicasets,verbs=get;list
// +kubebuilder:rbac:groups="",resources=serviceaccounts;configmaps;services,verbs=get;list;watch;create;patch;delete
// +kubebuilder:rbac:groups=apps,resources=deployments;daemonsets,verbs=get;list;watch;create;patch;delete
// +kubebuilder:rbac:groups=rbac.authorization.k8s.io,resources=roles;rolebindings;clusterroles;clusterrolebindings,verbs=get;list;watch
// +kubebuilder:rbac:groups=storage.k8s.io,resources=csidrivers,verbs=get;list;watch;create;patch;delete
// +kubebuilder:rbac:groups=security.openshift.io,resources=securitycontextconstraints,verbs=get;list;watch;create;patch;delete
//
// Active-usage gate: read-only LIST on the three storage kinds the
// disable/delete scan checks. The operator never creates, updates or deletes
// them — customer data stays out of the mutation surface. list-only: no
// watch, the gate re-checks on the retryable requeue and on spec/operand
// events.
//
// The scan is DRIVER-IDENTITY based and CLUSTER-WIDE — the CSI provisioner
// serves Bound PVs to any workload namespace, so PVCs/PVs outside the
// operand namespace count when they carry the profile's provisioner identity
// (spec.csi.driver or the volumeHandle prefix), and foreign-storage PVCs/PVs
// never do. PVCs are listed in the operand namespace only when bound to one
// of those PVs. The VolumeAttachment set covers EVERY driver-identity PV
// regardless of phase — a Released/mid-transition PV can still carry a live
// attachment, and that attachment blocks.
//
// VolumeAttachment lives in storage.k8s.io, NOT the core group — a marker
// under groups="" would generate a rule the API server never matches, so the
// manager SA's real list (apply.go, storagev1.VolumeAttachmentList) would be
// Forbidden and the gate would wedge fail-safe on every disable/delete.
// PVC/PV stay in core (""), correct. The envtest RBAC-authorization suite
// runs these exact lists with the manager SA against a real API server.
// +kubebuilder:rbac:groups="",resources=persistentvolumeclaims,verbs=list
// +kubebuilder:rbac:groups="",resources=persistentvolumes,verbs=list
// +kubebuilder:rbac:groups=storage.k8s.io,resources=volumeattachments,verbs=list
package v1alpha1

import (
	"k8s.io/apimachinery/pkg/runtime/schema"
	"sigs.k8s.io/controller-runtime/pkg/scheme"
)

var (
	// GroupVersion is group version used to register these objects.
	GroupVersion = schema.GroupVersion{Group: "quartet.ngxstorage.com", Version: "v1alpha1"}

	// SchemeBuilder is used to add go types to the GroupVersionKind scheme.
	SchemeBuilder = &scheme.Builder{GroupVersion: GroupVersion}

	// AddToScheme adds the types in this group-version to the given scheme.
	AddToScheme = SchemeBuilder.AddToScheme
)
